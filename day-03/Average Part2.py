#Average of three marks
mark1 = float(input("Please enter the marks for Quiz 1: "))
mark2 = float(input("Please enter the marks for Quiz 2: "))
mark3 = float(input("Please enter the marks for Quiz 3: "))
mark4 = float(input("Please enter the marks for Quiz 4: "))

average = (mark1 + mark2 + mark3 + mark4) / 4

print("Your average mark is: " f"{average: .2f}")
